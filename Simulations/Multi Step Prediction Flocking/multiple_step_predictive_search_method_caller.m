%%
clc;
clear;
close all;

%%
scale = 2; %1 -> 5 robots, 2 -> 20 robots, 3 -> 80 robots
obs_density = 2; % 1 -> 0.06m^-2, 2 -> 0.12m^-2, 3 -> 0.20m^-2
RepeatCount = 100;

%%
stepNumArr = 1:10; %number of predicted steps
NbestArr = 1:7; %beam width for multi-step search

tic;
for Repeat_i = 1:RepeatCount
    for stepNum_i = 1:length(stepNumArr)
        for Nbest_i = 1:length(NbestArr)

            rand_pos_num = Repeat_i; % ensure repeatability
            stepNum = stepNumArr(stepNum_i); %number of predicted steps
            Nbest = NbestArr(Nbest_i); %beam width for multi-step search

            run('multiple_step_predictive_search_method_call.m');

            % run('flocking_metric_plots.m');
            % close all;

            str = [...
                pwd, '\logs\', ...
                'scale', num2str(scale), '_', ...
                'obs', num2str(obs_density), '_', ...
                'stepNum', num2str(stepNum), '_', ...
                'Nbest', num2str(Nbest), '_', ...
                'Repeat', num2str(rand_pos_num), '.mat'];

            save(str, ...
                'dt', ...
                'sim_vel_list', ...
                'sim_kk', ...
                'quadNum', ...
                'migSpd', ...
                'sim_pos_list', ...
                'inter_agent_dist', ...
                'quad_rad_real', ...
                'sense_range', ...
                'quadK', ...
                'd_safety_rob', ...
                'migVel', ...
                'obs_pos_list', ...
                'obs_rad_list_real', ...
                'obsNum', ...
                'quad_rad', ...
                'd_safety_obs', ...
                'obs_rad'...
                );

            tS = toc;

            clc;
            fprintf('%d out of %d is done\nTime Remaining: %.1f minutes\n', ...
                (Repeat_i - 1) * length(stepNumArr) * length(NbestArr) + (stepNum_i - 1) * length(NbestArr) + Nbest_i, ...
                RepeatCount * length(stepNumArr) * length(NbestArr), ...
                (RepeatCount * length(stepNumArr) * length(NbestArr) - ((Repeat_i - 1) * length(stepNumArr) * length(NbestArr) + (stepNum_i - 1) * length(NbestArr) + Nbest_i)) / ((Repeat_i - 1) * length(stepNumArr) * length(NbestArr) + (stepNum_i - 1) * length(NbestArr) + Nbest_i) * tS / 60);

        end
    end
end
